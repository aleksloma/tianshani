// unit ტესტი ამოწმებს, რომ არც მონაცემებში, არც mock-ში არ გვხვდება; სერვერი რეალურ პასუხზე WARN-ს წერს.

/** შევსება: ყოველი ახალი შემთხვევა აქ ემატება (წყარო — ადმინის „შესწორებული პასუხები“ ან მომხმარებელი). */
export const NON_WORDS = [
  'ვჭედავარ', // ვასო, Round 3 — არ არსებობს („ვზივარ“ / „ვიჭედები“ იგულისხმებოდა)
];

/** რომელი არარსებული სიტყვებია ტექსტში. */
export function findNonWords(text) {
  const t = String(text || '');
  return NON_WORDS.filter((w) => t.includes(w));
}
